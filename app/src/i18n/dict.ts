/** "Sreda, 7. oktobar" / "Wednesday, 7 October" for a YYYY-MM-DD key. */
export function longDayLabel(key: string, lang: Lang): string {
  const d = new Date(key + 'T00:00:00')
  const dayName = WDAYS_LONG[lang][(d.getDay() + 6) % 7]
  return lang === 'en'
    ? `${dayName}, ${d.getDate()} ${MONTHS.en[d.getMonth()]}`
    : `${dayName}, ${d.getDate()}. ${MONTHS[lang][d.getMonth()]}`
}

export function shortDateLabel(key: string, lang: Lang): string {
  const d = new Date(key.slice(0, 10) + 'T00:00:00')
  return lang === 'en' ? `${d.getDate()} ${MONTHS.en[d.getMonth()]}` : `${d.getDate()}. ${MONTHS[lang][d.getMonth()]}`
}

export function monthYearLabel(key: string, lang: Lang): string {
  const d = new Date(key.slice(0, 10) + 'T00:00:00')
  return `${MONTHS[lang][d.getMonth()]} ${d.getFullYear()}.`.replace(/\.$/, lang === 'sr' ? '.' : '')
}
